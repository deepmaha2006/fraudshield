-- Migration 003 — e-mail ownership verification.
-- Alert e-mails are only sent to verified addresses so the service cannot
-- be used to mail arbitrary third parties. Accounts created before this
-- migration are grandfathered as verified.
SET search_path TO fraudshield;

ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TEXT;
UPDATE users SET email_verified_at = to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    WHERE email_verified_at IS NULL;

CREATE TABLE IF NOT EXISTS email_verifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TEXT NOT NULL,
    used_at    TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE INDEX IF NOT EXISTS idx_email_verifications_user ON email_verifications(user_id);
ENABLE ROW LEVEL SECURITY ON email_verifications;
ALTER TABLE email_verifications FORCE ROW LEVEL SECURITY;

UPDATE schema_meta SET version = 3 WHERE id = 1;
